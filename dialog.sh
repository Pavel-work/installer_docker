                 "Qdrant"       "  Qdrant      - векторная база AI" OFF \
                 "Ollama"       "  Ollama      - локальная LLM" OFF \
                 "Apache"       "  Apache      - веб-сервер HTTP" OFF \
                 "NginxProxy"   "  Nginx Proxy - управление прокси" OFF \
                 "Portainer"    "  Portainer   - управление Docker" OFF \
