#!/bin/bash

# Проверка наличия утилиты dialog
if ! command -v dialog &> /dev/null; then
    echo "Ошибка: утилита 'dialog' не установлена."
    echo "Установите: sudo apt install dialog"
    exit 1
fi

clear

# ==========================================
# 1. Приветствие
# ==========================================
dialog --backtitle "Docker Installer" \
       --title "Добро пожаловать" \
       --yes-label "Начать" --no-label "Выход" \
       --yesno "Добро пожаловать в установщик Docker!\n\nМастер поможет быстро установить и настроить сервисы." 10 70

[ $? -ne 0 ] && { clear; exit 0; }

# ==========================================
# 2. Выбор сервисов
# ==========================================
choices=$(dialog --stdout \
                 --backtitle "Docker Installer" \
                 --title "Выбор сервисов" \
                 --ok-label "Установить" --cancel-label "Отмена" \
                 --checklist "Отметьте сервисы (пробел - выбор):" 18 80 8 \
                 "PostgreSQL" "База данных PostgreSQL" OFF \
                 "Qdrant" "Векторная база Qdrant" OFF \
                 "Ollama" "Локальная LLM Ollama" OFF \
                 "Apache" "Веб-сервер Apache" OFF \
                 "NginxProxy" "Nginx Proxy Manager" OFF \
                 "Portainer" "Управление Docker" OFF \
                 "Supabase" "Supabase Full Stack" OFF \
                 "n8n" "Автоматизация n8n" OFF)

[ $? -ne 0 ] && { dialog --msgbox "Отменено" 6 50; clear; exit 0; }
[ -z "$choices" ] && { dialog --msgbox "Выберите хотя бы один сервис!" 6 50; clear; exit 1; }

clean_choices=$(echo "$choices" | xargs -n 1 | tr -d '"')
num_selected=$(echo "$clean_choices" | wc -l)

# ==========================================
# 3. Подтверждение
# ==========================================
services_list=$(echo "$clean_choices" | sed 's/^/    • /')

dialog --title "Подтверждение" \
       --yes-label "Установить" --no-label "Отмена" \
       --yesno "Будут установлены:\n\n  1. Docker Engine\n  2. Docker Compose\n  3. Сервисы (${num_selected} шт.):\n\n${services_list}\n\nПродолжить?" 16 70

[ $? -ne 0 ] && { clear; exit 0; }

# ==========================================
# 4. Установка
# ==========================================
dialog --infobox "\nУстановка Docker Engine...\n\n[████████░░░░░░░░░░░░░░░░] 40%\n" 8 60
sleep 2

dialog --infobox "\nDocker установлен!\n\nУстановка сервисов:\n\n$(echo "$clean_choices" | sed 's/^/    ⚙ /')\n\n[████████████████████░░] 85%\n" $((8 + num_selected)) 60
sleep 2

# ==========================================
# 5. Генерация данных
# ==========================================
service_info=""

for service in $clean_choices; do
    case "$service" in
        PostgreSQL)
            pass=$(openssl rand -base64 14)
            service_info="${service_info}
┌─────────────────────────────────────────
│ 📦 PostgreSQL
├─────────────────────────────────────────
│ Порт:        5432
│ Пользователь: postgres
│ Пароль:      $pass
│ URL:         localhost:5432
└─────────────────────────────────────────"
            ;;
        Qdrant)
            service_info="${service_info}
┌─────────────────────────────────────────
│ 📦 Qdrant
├─────────────────────────────────────────
│ Порт REST:   6333
│ Порт gRPC:   6334
│ URL:         http://localhost:6333
└─────────────────────────────────────────"
            ;;
        Ollama)
            service_info="${service_info}
┌─────────────────────────────────────────
│ 📦 Ollama
├─────────────────────────────────────────
│ Порт:        11434
│ API:         http://localhost:11434
│ Пример:      ollama pull llama2
└─────────────────────────────────────────"
            ;;
        Apache)
            service_info="${service_info}
┌─────────────────────────────────────────
│ 📦 Apache
├─────────────────────────────────────────
│ HTTP:        80
│ HTTPS:       443
│ URL:         http://localhost
└─────────────────────────────────────────"
            ;;
        NginxProxy)
            pass=$(openssl rand -base64 14)
            service_info="${service_info}
┌─────────────────────────────────────────
│ 📦 Nginx Proxy Manager
├─────────────────────────────────────────
│ HTTP:        80
│ HTTPS:       443
│ Панель:      http://localhost:81
│ Email:       admin@example.com
│ Пароль:      $pass
└─────────────────────────────────────────"
            ;;
        Portainer)
            service_info="${service_info}
┌─────────────────────────────────────────
│ 📦 Portainer
├─────────────────────────────────────────
│ HTTP:        9000
│ HTTPS:       9443
│ URL:         https://localhost:9443
└─────────────────────────────────────────"
            ;;
        Supabase)
            service_info="${service_info}
┌─────────────────────────────────────────
│ 📦 Supabase
├─────────────────────────────────────────
│ Kong:        http://localhost:8000
│ Studio:      http://localhost:8001
│ Postgres:    localhost:54322
└─────────────────────────────────────────"
            ;;
        n8n)
            service_info="${service_info}
┌─────────────────────────────────────────
│ 📦 n8n
├─────────────────────────────────────────
│ Порт:        5678
│ URL:         http://localhost:5678
└─────────────────────────────────────────"
            ;;
    esac
done

# ==========================================
# 6. Финальное окно - компактное
# ==========================================
dialog --title "✓ ГОТОВО" \
       --msgbox "\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n   ✓ УСТАНОВКА ЗАВЕРШЕНА!\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n\nУстановлено сервисов: ${num_selected}\n\n${service_info}\n\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n⚠️  СОХРАНИТЕ ЭТИ ДАННЫЕ!  ⚠️\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n" 25 70

# ==========================================
# 7. Вывод ВСЕХ данных в терминал (БЕЗ ПРОКРУТКИ!)
# ==========================================
clear

echo ""
echo "╔══════════════════════════════════════════════════════════╗"
echo "║                                                          ║"
echo "║           ✓  УСТАНОВКА УСПЕШНО ЗАВЕРШЕНА!  ✓            ║"
echo "║                                                          ║"
echo "╚══════════════════════════════════════════════════════════╝"
echo ""
echo "Установлено сервисов: ${num_selected}"
echo ""
echo "═══════════════════════════════════════════════════════════"
echo "                    ДАННЫЕ ДОСТУПА:"
echo "═══════════════════════════════════════════════════════════"
echo ""
echo -e "$service_info"
echo ""
echo "═══════════════════════════════════════════════════════════"
echo "  ⚠️  ВАЖНО: Сохраните эти данные в безопасном месте!"
echo "  • Пароли сгенерированы автоматически"
echo "  • Для изменения отредактируйте .env файлы"
echo "═══════════════════════════════════════════════════════════"
echo ""
